//! Content-hashed static assets for the UI shell.
//!
//! Phase 1 ships one hand-authored stylesheet (`static/app.css`, embedded via
//! `include_str!`). Assets are served from `/static/{hash}/{file}` where
//! `{hash}` is the full sha256 of the file contents, computed once per
//! process behind a `OnceLock`. Because the URL changes whenever the content
//! changes, responses carry `Cache-Control: public, max-age=31536000,
//! immutable`; a hash mismatch is a 404 so a stale URL can never serve the
//! wrong bytes.
//!
//! This is deliberately a plain handler rather than `tower_http::ServeDir`:
//! the embedded single-file approach needs no `fs` feature on tower-http and
//! keeps the binary self-contained (spec §2.3: no node build, no runtime
//! template or asset dependency).

use axum::extract::{OriginalUri, Path, State};
use axum::http::{header, HeaderMap, StatusCode};
use axum::response::{IntoResponse, Response};
use sha2::{Digest, Sha256};
use std::sync::OnceLock;

use star_common::{ApiError, AppState};

use crate::embed;

/// The shell stylesheet, embedded at compile time.
pub const APP_CSS: &str = include_str!("../static/app.css");

/// Full sha256 hex digest of [`APP_CSS`], computed once.
pub fn app_css_hash() -> &'static str {
    static HASH: OnceLock<String> = OnceLock::new();
    HASH.get_or_init(|| hex_sha256(APP_CSS.as_bytes()))
}

/// Absolute URL for the stylesheet, including its content hash.
pub fn app_css_url() -> String {
    format!("/static/{}/app.css", app_css_hash())
}

fn hex_sha256(bytes: &[u8]) -> String {
    let digest = Sha256::digest(bytes);
    let mut hex = String::with_capacity(digest.len() * 2);
    for byte in digest {
        use std::fmt::Write as _;
        let _ = write!(hex, "{byte:02x}");
    }
    hex
}

/// Serve an embedded asset by content hash. `GET /static/{hash}/{file}`.
///
/// 404s when either the file name is unknown or the hash does not match the
/// current content — both mean "the client is holding a URL from a previous
/// build", which a cache-immutable response must never answer with different
/// bytes. On match, the response is immutable-cacheable.
pub async fn serve_static(
    State(_state): State<AppState>,
    Path((hash, file)): Path<(String, String)>,
) -> Result<Response, ApiError> {
    let (body, content_type) = match file.as_str() {
        "app.css" => (APP_CSS, "text/css; charset=utf-8"),
        _ => return Err(ApiError::NotFound),
    };

    if hash != app_css_hash() {
        return Err(ApiError::NotFound);
    }

    let mut headers = HeaderMap::new();
    headers.insert(
        header::CONTENT_TYPE,
        header::HeaderValue::from_static(content_type),
    );
    headers.insert(
        header::CACHE_CONTROL,
        header::HeaderValue::from_static("public, max-age=31536000, immutable"),
    );

    Ok((StatusCode::OK, headers, body).into_response())
}

// ---------------------------------------------------------------------------
// The embedded front end: the Svelte bundle and the vendored Canvas layer
// ---------------------------------------------------------------------------

/// One embedded file. Generated by `build.rs` from `migration/ui/build` and
/// `migration/ui/static`.
pub type EmbeddedAsset = embed::Asset;

/// Find an embedded file by URL path.
///
/// `ASSETS` comes out of a `BTreeMap`, so it is sorted and this is a binary search
/// over the ~330 files the front end ships instead of a scan.
pub fn embedded(path: &str) -> Option<&'static EmbeddedAsset> {
    embed::ASSETS
        .binary_search_by(|asset| asset.path.as_bytes().cmp(path.as_bytes()))
        .ok()
        .map(|index| &embed::ASSETS[index])
}

/// The immutable URL for one Canvas stylesheet: `/canvas/{rev}/{variant}/{name}.css`.
///
/// The revision is the point. `/_app/**` needs no such treatment because Vite puts
/// a hash in the filename, but these sheets keep Canvas' names — the only names the
/// compiled output can have, since they are what `app/stylesheets/bundles/<name>.scss`
/// produces. Without a revision in the URL the shell would have to serve them with
/// revalidation on every page view, which is exactly the cost the static-bundle
/// decision exists to remove.
///
/// Falls back to the unversioned path when the sheet is not embedded (only reachable
/// if `embed/shell-map.txt` names a bundle build.rs does not validate — it does).
pub fn canvas_href(variant: &str, bundle: &str) -> String {
    match embedded(&format!("/canvas/{variant}/{bundle}.css")) {
        Some(asset) => format!("/canvas/{}/{variant}/{bundle}.css", asset.rev),
        None => format!("/canvas/{variant}/{bundle}.css"),
    }
}

/// Split a request path into (table key, revision claimed by the URL).
///
/// Only `/canvas/**` has the two shapes: with a revision (what the shell emits) and
/// without (what `src/lib/canvasStyles.ts` appends during a client-side navigation,
/// where the SPA knows bundle names but not their hashes). Everything else — Vite's
/// `/_app/**`, and the fonts and images Canvas' own sheets reference by root-relative
/// path — is looked up verbatim.
/// Whether the path is one of the embedded front-end assets.
///
/// The shell's fallback answers the assets itself; every other path belongs
/// to the application (the front door).
pub fn is_embedded_path(path: &str) -> bool {
    resolve(path).is_some()
}

fn resolve(path: &str) -> Option<(String, Option<String>)> {
    let Some(rest) = path.strip_prefix("/canvas/") else {
        return Some((path.to_string(), None));
    };
    let segments: Vec<&str> = rest.split('/').collect();
    let is_variant = |seg: &str| seg == "normal_contrast" || seg == "high_contrast";
    let is_rev = |seg: &str| seg.len() == 8 && seg.bytes().all(|byte| byte.is_ascii_hexdigit());
    match segments.as_slice() {
        [variant, file] if is_variant(variant) && file.ends_with(".css") => {
            Some((format!("/canvas/{variant}/{file}"), None))
        }
        [rev, variant, file] if is_rev(rev) && is_variant(variant) && file.ends_with(".css") => {
            Some((
                format!("/canvas/{variant}/{file}"),
                Some((*rev).to_string()),
            ))
        }
        _ => None,
    }
}

/// Cache policy per family, and the reason each one is what it is.
fn cache_policy(key: &str, rev_claimed: bool) -> &'static str {
    if key.starts_with("/_app/") {
        // Vite content-hashes these filenames: identical URL cannot mean new bytes.
        return "public, max-age=31536000, immutable";
    }
    if key.starts_with("/canvas/") && rev_claimed {
        // The revision in the URL plays the same role for the Canvas sheets.
        return "public, max-age=31536000, immutable";
    }
    // Fonts and images carry the fixed paths written inside Canvas' own sheets, so
    // they cannot be content-addressed without rewriting the sheets; the unversioned
    // canvas form is reached from the SPA mid-navigation, before it has a revision.
    // Both get a short life plus revalidation, and the ETag makes revalidation a
    // 304 with no body.
    "public, max-age=86400, must-revalidate"
}

/// Serve one embedded asset.
///
/// Registered as the shell router's fallback, so it sees every path the page table
/// does not — including mistyped `/api/v1` paths, which is why a miss answers with a
/// bare 404 rather than an `ApiError`: that keeps the response byte-identical to
/// axum's own default fallback, which the workspace's unmatched-path tests assert.
pub async fn serve_embedded(
    method: axum::http::Method,
    OriginalUri(uri): OriginalUri,
    headers: HeaderMap,
) -> Response {
    let not_found = || StatusCode::NOT_FOUND.into_response();

    // Only reads have an asset answer. A POST to `/fonts/x.woff2` is a mistake, and the
    // honest reply is the same 404 an unknown path gets — not the bytes of a file.
    if method != axum::http::Method::GET && method != axum::http::Method::HEAD {
        return not_found();
    }

    let Some((key, claimed_rev)) = resolve(uri.path()) else {
        return not_found();
    };
    let Some(asset) = embedded(&key) else {
        return not_found();
    };
    // A stale revision means the client is holding a link from a previous build.
    // `serve_static` refuses that for app.css for the same reason: a cache-immutable
    // URL must never answer with different bytes.
    let rev_claimed = claimed_rev.is_some();
    if claimed_rev.as_deref().is_some_and(|rev| rev != asset.rev) {
        return not_found();
    }

    let etag = format!("\"{}\"", asset.rev);
    if headers
        .get(header::IF_NONE_MATCH)
        .and_then(|value| value.to_str().ok())
        == Some(etag.as_str())
    {
        return (StatusCode::NOT_MODIFIED, [(header::ETAG, etag)]).into_response();
    }

    (
        StatusCode::OK,
        [
            (header::CONTENT_TYPE, asset.mime.to_string()),
            (
                header::CACHE_CONTROL,
                cache_policy(&key, rev_claimed).to_string(),
            ),
            (header::ETAG, etag),
            (header::X_CONTENT_TYPE_OPTIONS, "nosniff".to_string()),
        ],
        asset.bytes,
    )
        .into_response()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn app_css_hash_is_a_sha256_hex_digest() {
        let hash = app_css_hash();
        assert_eq!(hash.len(), 64);
        assert!(hash.chars().all(|c| c.is_ascii_hexdigit()));
        // Stable across calls (OnceLock) and equal to a fresh computation.
        assert_eq!(hash, hex_sha256(APP_CSS.as_bytes()));
    }

    #[test]
    fn app_css_url_embeds_the_hash() {
        assert_eq!(app_css_url(), format!("/static/{}/app.css", app_css_hash()));
    }

    #[test]
    fn hex_sha256_matches_known_vector() {
        // sha256("") — well-known digest, guards the hex encoding loop.
        assert_eq!(
            hex_sha256(b""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
    }

    #[test]
    fn embedded_table_is_sorted_and_unique() {
        // binary_search is only correct on sorted input, and build.rs produces the
        // table from a BTreeMap — this pins that contract in the crate that reads it.
        let paths: Vec<&str> = embed::ASSETS.iter().map(|asset| asset.path).collect();
        assert!(
            paths.windows(2).all(|pair| pair[0] < pair[1]),
            "ASSETS unsorted"
        );
        assert!(
            embed::ASSETS.len() > 100,
            "only {} embedded assets — did migration/ui/build get committed?",
            embed::ASSETS.len()
        );
        for asset in embed::ASSETS {
            assert_eq!(asset.rev.len(), 8, "{} has a bad revision", asset.path);
            assert!(!asset.bytes.is_empty(), "{} embeds no bytes", asset.path);
        }
    }

    #[test]
    fn the_canvas_layer_and_the_bundle_are_both_embedded() {
        // Three roots, three proofs, chosen because each one breaks the page in a
        // different way if it is missing: no tokens means an unstyled cascade, no
        // woff2 means Lato Extended silently falls back, no entry means a blank page.
        for path in [
            "/canvas/normal_contrast/tokens.css",
            "/canvas/normal_contrast/common.css",
            "/canvas/high_contrast/common.css",
            "/fonts/lato/extended/Lato-Regular.woff2",
            "/favicon.svg",
        ] {
            assert!(embedded(path).is_some(), "{path} is not embedded");
        }
        assert!(
            embed::ASSETS
                .iter()
                .any(|asset| asset.path.starts_with("/_app/immutable/entry/start.")),
            "no SvelteKit start entry embedded"
        );
    }

    #[test]
    fn canvas_href_versioning_follows_the_embedded_bytes() {
        let href = canvas_href("normal_contrast", "common");
        let (key, claimed) = resolve(&href).expect("shell-emitted href must resolve");
        assert_eq!(key, "/canvas/normal_contrast/common.css");
        let asset = embedded(&key).expect("common.css embedded");
        assert_eq!(
            claimed.as_deref(),
            Some(asset.rev),
            "href {href} must carry the revision of the bytes it addresses"
        );
    }

    #[test]
    fn resolve_accepts_both_canvas_shapes_and_rejects_others() {
        assert_eq!(
            resolve("/canvas/normal_contrast/common.css").map(|(key, rev)| (key, rev.is_some())),
            Some(("/canvas/normal_contrast/common.css".to_string(), false))
        );
        assert_eq!(
            resolve("/canvas/de10a2be/high_contrast/tokens.css"),
            Some((
                "/canvas/high_contrast/tokens.css".to_string(),
                Some("de10a2be".to_string())
            ))
        );
        // Not a variant directory, and a revision that is not 8 hex chars.
        assert!(resolve("/canvas/rtl/common.css").is_none());
        assert!(resolve("/canvas/zzzzzzzz/normal_contrast/common.css").is_none());
        // Unknown sheet shapes fall through to a table miss, not a parse panic.
        assert_eq!(
            resolve("/fonts/lato/extended/Lato-Regular.woff2").map(|(key, _)| key),
            Some("/fonts/lato/extended/Lato-Regular.woff2".to_string())
        );
        assert!(resolve("/_app/immutable/chunks/x.js").is_some());
    }

    #[test]
    fn cache_policy_matches_how_each_family_is_addressed() {
        assert_eq!(
            cache_policy("/_app/immutable/nodes/0.abc123.js", false),
            "public, max-age=31536000, immutable"
        );
        assert_eq!(
            cache_policy("/canvas/normal_contrast/common.css", true),
            "public, max-age=31536000, immutable"
        );
        // Unversioned sheet (SPA injected mid-navigation), fonts and images: their
        // URLs cannot carry a revision, so they revalidate instead.
        assert_eq!(
            cache_policy("/canvas/normal_contrast/common.css", false),
            "public, max-age=86400, must-revalidate"
        );
        assert_eq!(
            cache_policy("/fonts/canvas-icons.woff", false),
            "public, max-age=86400, must-revalidate"
        );
    }
}
