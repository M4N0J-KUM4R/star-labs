//! Integration tests for the Phase 5 files slice: update (PUT /files/{id}),
//! public_url, context-scoped show and file_ref.
//!
//! Pins ACTUAL handler behavior:
//! - PUT /files/{id} renames display_name for teachers (200, attachment_json
//!   shape); renaming onto a sibling display_name answers 409 with Canvas's
//!   duplicate message unless on_duplicate='rename' (which appends "-1").
//! - Students cannot update files (403).
//! - GET /files/{id}/public_url answers `{ public_url }` pointing at the
//!   download route with the file's uuid as the verifier.
//! - GET /courses/{courseId}/files/{id} hides hidden files from students
//!   (404) while teachers still see them (200).
//! - GET /courses/{courseId}/files/file_ref/{uuid} resolves a file by uuid and
//!   answers 404 for unknown uuids.
//!
//! Skipped cleanly when DATABASE_URL is not set. Run with:
//! DATABASE_URL=postgres://... cargo test -p star-files

use axum_test::TestServer;
use serde_json::{json, Value};
use sqlx::PgPool;
use star_common::AppState;

const JWT_SECRET: &str = "test-jwt-secret";

fn run_prefix() -> String {
    use std::sync::atomic::{AtomicU32, Ordering};
    static N: AtomicU32 = AtomicU32::new(0);
    let n = N.fetch_add(1, Ordering::Relaxed);
    format!(
        "filint-{}-{}",
        std::process::id(),
        chrono::Utc::now().timestamp_millis() + n as i64
    )
}

async fn setup() -> Option<(TestServer, PgPool, String)> {
    let db_url = std::env::var("DATABASE_URL").ok()?;

    let pool = sqlx::postgres::PgPoolOptions::new()
        .max_connections(5)
        .acquire_timeout(std::time::Duration::from_secs(10))
        .connect(&db_url)
        .await
        .expect("connect to Postgres");

    star_db::MIGRATOR.run(&pool).await.expect("run migrations");

    let state = AppState {
        db: pool.clone(),
        jwt_secret: JWT_SECRET.to_string(),
    };
    let server = TestServer::new(star_files::router().with_state(state)).expect("build TestServer");
    Some((server, pool, run_prefix()))
}

async fn seed_user(pool: &PgPool, prefix: &str, name: &str, role: &str) -> i64 {
    sqlx::query_scalar(
        "INSERT INTO users (name, email, password_hash, role) VALUES ($1, $2, $3, $4) RETURNING id",
    )
    .bind(name)
    .bind(format!("{prefix}-{name}@test.local"))
    .bind("not-a-real-hash")
    .bind(role)
    .fetch_one(pool)
    .await
    .expect("seed user")
}

async fn seed_course(pool: &PgPool, prefix: &str, name: &str) -> i64 {
    sqlx::query_scalar("INSERT INTO courses (name, course_code) VALUES ($1, $2) RETURNING id")
        .bind(name)
        .bind(format!("{prefix}-{name}"))
        .fetch_one(pool)
        .await
        .expect("seed course")
}

async fn seed_enrollment(pool: &PgPool, user_id: i64, course_id: i64, role: &str) {
    sqlx::query("INSERT INTO enrollments (user_id, course_id, role) VALUES ($1, $2, $3)")
        .bind(user_id)
        .bind(course_id)
        .bind(role)
        .execute(pool)
        .await
        .expect("seed enrollment");
}

/// Seed a metadata-only file row; display_name defaults to filename (Canvas
/// infer_display_name) and uuid defaults to the md5 generated by the column.
async fn seed_file(pool: &PgPool, course_id: i64, uploader_id: i64, name: &str) -> i64 {
    seed_file_opt(pool, course_id, uploader_id, name, false, None).await
}

/// Seed a file row with explicit hidden/uuid flags (file_ref resolves uuids).
async fn seed_file_opt(
    pool: &PgPool,
    course_id: i64,
    uploader_id: i64,
    name: &str,
    hidden: bool,
    uuid: Option<&str>,
) -> i64 {
    sqlx::query_scalar(
        r#"
        INSERT INTO files (course_id, uploader_id, filename, display_name,
                           content_type, size, folder, hidden, uuid)
        VALUES ($1, $2, $3, $3, 'text/plain', 10, 'unfiled', $4, $5)
        RETURNING id
        "#,
    )
    .bind(course_id)
    .bind(uploader_id)
    .bind(name)
    .bind(hidden)
    .bind(uuid)
    .fetch_one(pool)
    .await
    .expect("seed file")
}

fn auth(user_id: i64, role: &str) -> String {
    let token = star_auth::create_token(user_id, role, JWT_SECRET).expect("mint token");
    format!("Bearer {token}")
}

async fn cleanup(pool: &PgPool, prefix: &str) {
    // usage_rights and folders key on (context_type, context_id) with no FK to
    // courses, so they must go before the course rows themselves.
    let _ = sqlx::query(
        "DELETE FROM usage_rights WHERE context_type = 'Course' \
         AND context_id IN (SELECT id FROM courses WHERE course_code LIKE $1)",
    )
    .bind(format!("{prefix}%"))
    .execute(pool)
    .await;
    let _ = sqlx::query(
        "DELETE FROM folders WHERE context_type = 'Course' \
         AND context_id IN (SELECT id FROM courses WHERE course_code LIKE $1)",
    )
    .bind(format!("{prefix}%"))
    .execute(pool)
    .await;
    let _ = sqlx::query("DELETE FROM courses WHERE course_code LIKE $1")
        .bind(format!("{prefix}%"))
        .execute(pool)
        .await;
    let _ = sqlx::query("DELETE FROM users WHERE email LIKE $1")
        .bind(format!("{prefix}%@test.local"))
        .execute(pool)
        .await;
}

#[tokio::test]
async fn update_file_renames_display_name() {
    let Some((server, pool, prefix)) = setup().await else {
        println!("SKIP: DATABASE_URL not set");
        return;
    };
    let teacher = seed_user(&pool, &prefix, "UpdTeacher", "teacher").await;
    let course = seed_course(&pool, &prefix, "UpdCourse").await;
    seed_enrollment(&pool, teacher, course, "teacher").await;
    let file = seed_file(&pool, course, teacher, "notes.txt").await;

    // Canvas files#api_update answers the updated attachment_json.
    let resp = server
        .put(&format!("/files/{file}"))
        .add_header(axum::http::header::AUTHORIZATION, auth(teacher, "teacher"))
        .json(&json!({ "name": "lecture.txt" }))
        .await;
    assert_eq!(resp.status_code(), 200, "body: {}", resp.text());
    let body: Value = resp.json();
    assert_eq!(body["id"].as_i64(), Some(file));
    assert_eq!(body["display_name"], "lecture.txt");
    assert_eq!(body["filename"], "notes.txt");
    assert_eq!(body["content-type"], "text/plain");
    assert_eq!(body["mime_class"], "text");
    assert_eq!(body["upload_status"], "success");

    cleanup(&pool, &prefix).await;
}

#[tokio::test]
async fn update_file_duplicate_name_conflicts_and_rename_suffix() {
    let Some((server, pool, prefix)) = setup().await else {
        println!("SKIP: DATABASE_URL not set");
        return;
    };
    let teacher = seed_user(&pool, &prefix, "DupTeacher", "teacher").await;
    let course = seed_course(&pool, &prefix, "DupCourse").await;
    seed_enrollment(&pool, teacher, course, "teacher").await;
    let first = seed_file(&pool, course, teacher, "notes.txt").await;
    let second = seed_file(&pool, course, teacher, "draft.txt").await;

    // Renaming onto a sibling display_name is a Canvas 409 duplicate conflict.
    let resp = server
        .put(&format!("/files/{second}"))
        .add_header(axum::http::header::AUTHORIZATION, auth(teacher, "teacher"))
        .json(&json!({ "name": "notes.txt" }))
        .await;
    assert_eq!(resp.status_code(), 409, "body: {}", resp.text());
    let body: Value = resp.json();
    assert!(
        body["message"]
            .as_str()
            .is_some_and(|m| m.contains("file already exists")),
        "body: {body}"
    );

    // on_duplicate='rename' resolves it with the "-1" suffix.
    let resp = server
        .put(&format!("/files/{second}"))
        .add_header(axum::http::header::AUTHORIZATION, auth(teacher, "teacher"))
        .json(&json!({ "name": "notes.txt", "on_duplicate": "rename" }))
        .await;
    assert_eq!(resp.status_code(), 200, "body: {}", resp.text());
    let body: Value = resp.json();
    assert_eq!(body["display_name"], "notes-1.txt");
    assert_eq!(body["id"].as_i64(), Some(second));
    assert_ne!(body["id"].as_i64(), Some(first));

    cleanup(&pool, &prefix).await;
}

