// Generate the brandable token sheet from Canvas' own inputs, instead of a
// hand-copied list of hex values.
//
// Ground truth, in the order Canvas uses it:
//   app/stylesheets/brandable_variables.json  — the 47 variables and defaults
//   lib/brandable_css.rb:148  brand_variable_value — how a $ref resolves
//   lib/brandable_css.rb:168  computed_variables   — the 14 derived names
//   lib/brandable_css.rb:205  all_brand_variable_values_as_css — the :root shape
//   lib/brandable_css.rb:223  high_contrast_overrides — the 2 HC replacements
//   gems/canvas_color/lib/canvas_color.rb:328,346 — the lighten/darken math
//
// The math is deliberately re-implemented rather than approximated, because the
// difference is visible: darken(#273540, 15%) is #172029 here and #1B252D if you
// mix in HSL instead of subtracting channel-wise with integer truncation.
//
// Usage: CANVAS_SRC=~/lms-migration/canvas-src node scripts/build-brandable-tokens.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const canvasSrc = process.env.CANVAS_SRC;
if (!canvasSrc) throw new Error('CANVAS_SRC is not set');
const ui = resolve(dirname(new URL(import.meta.url).pathname), '..');

const spec = JSON.parse(readFileSync(resolve(canvasSrc, 'app/stylesheets/brandable_variables.json'), 'utf8'));

/** @type {Map<string, {name: string, type: string, def: string}>} */
const variables = new Map();
for (const group of spec) {
	for (const v of group.variables) {
		if (v.type === 'textarea' || v.default === undefined) continue;
		variables.set(v.variable_name, { name: v.variable_name, type: v.type, def: String(v.default) });
	}
}

// brandable_css.rb:223 — the high-contrast sheet swaps exactly these two.
const HC_OVERRIDES = { 'ic-brand-primary': '#0A5A9E', 'ic-link-color': '#09508C' };

// brandable_css.rb:168 — the derived set, in Canvas' own order.
const COMPUTED = [
	['ic-brand-primary', 'darken', 5],
	['ic-brand-primary', 'darken', 10],
	['ic-brand-primary', 'darken', 15],
	['ic-brand-primary', 'lighten', 5],
	['ic-brand-primary', 'lighten', 10],
	['ic-brand-primary', 'lighten', 15],
	['ic-brand-button--primary-bgd', 'darken', 5],
	['ic-brand-button--primary-bgd', 'darken', 15],
	['ic-brand-button--secondary-bgd', 'darken', 5],
	['ic-brand-button--secondary-bgd', 'darken', 15],
	['ic-brand-font-color-dark', 'lighten', 15],
	['ic-brand-font-color-dark', 'lighten', 28],
	['ic-link-color', 'darken', 10],
	['ic-link-color', 'lighten', 10]
];

function rgb(hex) {
	const h = hex.replace('#', '');
	return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
}

const HEXVAL = '0123456789ABCDEF';
const toHex = (v) => HEXVAL[(v >> 4) & 15] + HEXVAL[v & 15];

// canvas_color.rb:328 / :346. `.to_i` truncates each channel, so floor matters.
const lighten = (hex, amt) =>
	'#' + rgb(hex).map((c) => toHex(c + Math.trunc((255 - c) * amt))).join('');
const darken = (hex, amt) => '#' + rgb(hex).map((c) => toHex(c - Math.trunc(c * amt))).join('');

/** Resolve to the literal CanvasColor would receive (brand_variable_value, css_urls: false). */
function literal(name, seen = new Set()) {
	const v = variables.get(name);
	if (!v) throw new Error(`unknown brandable variable ${name}`);
	if (v.def.startsWith('$')) return literal(v.def.slice(1), seen);
	if (seen.has(name)) throw new Error(`cycle at ${name}`);
	seen.add(name);
	return v.def;
}

/** The value the CSS sheet declares (brand_variable_value, css_urls: true). */
function asCss(v) {
	if (v.def.startsWith('$')) return `var(--${v.def.slice(1)})`;
	if (v.type === 'image') {
		// Canvas emits url('<name>') and lets Rails resolve it against the asset
		// host. We serve the vendored copies from the bundle root, so the path has
		// to keep its /images/ prefix; this is the one intentional deviation from
		// all_brand_variable_values_as_css's byte output.
		return v.def ? `url('${v.def}')` : '';
	}
	if (v.type === 'percentage') return v.def;
	return v.def;
}

function sheet(overrides, label) {
	for (const [k, val] of Object.entries(overrides)) if (variables.has(k)) variables.get(k).def = val;
	const lines = [];
	for (const [name, ref, pct] of COMPUTED) {
		const color = literal(name);
		if (!color.startsWith('#')) continue;
		const out = ref === 'darken' ? darken(color, pct / 100) : lighten(color, pct / 100);
		lines.push(`\t--${name}-${ref}ed-${pct}: ${out};`);
	}
	for (const v of variables.values()) lines.push(`\t--${v.name}: ${asCss(v)};`);
	return `/* Generated by scripts/build-brandable-tokens.mjs from ${label}.\n` +
		`   Do not hand-edit: the source of truth is canvas-src/app/stylesheets/brandable_variables.json\n` +
		`   plus the derivations in lib/brandable_css.rb. Rerun npm run tokens:canvas. */\n` +
		`:root {\n${lines.join('\n')}\n}\n`;
}

const normal = variables;
// static/, not src/styles/, because the two sheets are chosen per request from
// ENV.use_high_contrast. Anything Vite bundles is fixed at build time, so a
// bundled token sheet cannot switch — and a sheet in static/ ships byte-for-byte
// as generated, which is what makes the diff against Canvas reviewable.
const out1 = resolve(ui, 'static/canvas/normal_contrast/tokens.css');
mkdirSync(dirname(out1), { recursive: true });
writeFileSync(out1, sheet({}, 'canvas-src/app/stylesheets/brandable_variables.json'));

// HC sheet: same variables, two swapped before the derivations run.
for (const v of normal.values()) {
	if (v.name === 'ic-brand-primary') v.def = '#2B7ABC';
	if (v.name === 'ic-link-color') v.def = '#0E68B3';
}
const out2 = resolve(ui, 'static/canvas/high_contrast/tokens.css');
mkdirSync(dirname(out2), { recursive: true });
writeFileSync(out2, sheet(HC_OVERRIDES, 'brandable_variables.json + high_contrast_overrides'));

console.log(`wrote tokens.css (${variables.size} vars + ${COMPUTED.length} derived) into static/canvas/<variant>/`);

// Self-check, and the reason this is generated instead of hand-written: a name a
// bundle reads but no sheet defines renders as an invalid-at-computed-value-time
// declaration, which is a silent difference from Canvas. Two names are expected to
// be unread here because Canvas leaves them undefined too: they are set by
// component JS at runtime (`--size` by InstUI's Avatar,
// `--revision-button-hover-color` by the wiki revision slider). Anything else is
// a missing token.
const EXPECTED_UNDEFINED = new Set(['size', 'revision-button-hover-color']);
const { readdirSync, existsSync } = await import('node:fs');
let problems = 0;
for (const variant of ['normal_contrast', 'high_contrast']) {
	const dir = resolve(ui, 'static/canvas', variant);
	if (!existsSync(dir)) continue;
	const defined = new Set(
		[...readFileSync(resolve(dir, 'tokens.css'), 'utf8').matchAll(/^\s*--([a-zA-Z0-9_-]+):/gm)].map((m) => m[1])
	);
	for (const file of readdirSync(dir)) {
		if (file === 'tokens.css' || !file.endsWith('.css')) continue;
		const text = readFileSync(resolve(dir, file), 'utf8');
		for (const m of text.matchAll(/var\(--([a-zA-Z0-9_-]+)/g)) {
			if (!defined.has(m[1]) && !EXPECTED_UNDEFINED.has(m[1])) {
				console.error(`${variant}/${file}: --${m[1]} is read but never defined`);
				problems++;
			}
		}
	}
}
if (problems) {
	console.error(
		`\n${problems} undefined token reference(s). Add the variable to ${'canvas-src/app/stylesheets/'}brandable_variables.json's generated sheet, or confirm Canvas leaves it unset as well.`
	);
	process.exit(1);
}
console.log('token coverage: every var(--ic-*) a bundle reads is defined');

