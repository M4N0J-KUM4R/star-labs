#!/usr/bin/env python3
"""Generate the capability ledger.

The route map says which crate owns which Canvas route. The ledger says what
that means for the migration: for every Canvas controller — one capability —
where the port's code lives, how many recorded answers it has, how many of
them the port reproduces, what the failures look like, and whether the
capability is covered by the corpus at all.

The numbers are read from committed artefacts: the parity manifest (the
Canvas routes), the corpus (the recorded answers) and the replay report
(what the port answered). Nothing here is a judgement call except the
verdict column, which is derived from the counts.
"""

from __future__ import annotations

import collections
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from gen_knowledge import (  # noqa: E402
    REPO,
    api_shape,
    canvas_controller_file,
    recorded_cases,
    replay_status,
    star_registrations,
)

ID_SEGMENT = re.compile(r"^\d+$|^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$", re.I)


def case_shape(path: str) -> str:
    """The shape of a recorded request: its ids collapsed.

    The manifest's routes name their parameters (`:id`, `{}`); a recorded
    request carries the concrete id (6, a uuid), so the id segments have to
    be collapsed the same way.
    """
    if path.startswith("/api/v1"):
        path = path[len("/api/v1"):]
    parts = [("{}" if ID_SEGMENT.match(seg) else seg) for seg in path.split("/")]
    return "/".join(parts) or "/"

MANIFEST = REPO / "migration" / "parity" / "canvas_manifest.json"
REPORT = REPO / "migration" / "rust" / "app-cases" / "replay-report.md"


def load_manifest() -> list[dict]:
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    routes = data.get("routes") if isinstance(data, dict) else data
    if isinstance(routes, dict):
        routes = list(routes.values())
    return [r for r in routes if isinstance(r, dict) and r.get("path")]


def report_failures() -> dict[str, list[str]]:
    """Case -> the difference shapes the report lists for it."""
    if not REPORT.is_file():
        return {}
    text = REPORT.read_text(encoding="utf-8", errors="ignore")
    out: dict[str, list[str]] = {}
    for block in re.split(r"^### ", text, flags=re.M)[1:]:
        name = block.split("\n", 1)[0].strip()
        shapes = []
        for match in re.finditer(r"^at ([^\n(]+?)(?: \(|,\s*line)", block, re.M):
            where = match.group(1).strip()
            kind = re.search(r"^at [^\n(]+?\(([^)]*)\)", block[match.start():], re.M)
            shapes.append(f"{where}" + (f" ({kind.group(1)})" if kind else ""))
        out[name] = shapes
    return out


def main() -> int:
    routes = load_manifest()
    cases = recorded_cases()
    verdict = replay_status()
    failures = report_failures()
    registrations = star_registrations()

    # Canvas controller -> its routes, and the shape of each.
    by_controller: dict[str, list[dict]] = collections.defaultdict(list)
    for route in routes:
        by_controller[route.get("controller", "unknown")].append(route)

    # The shape of every recorded request, so a case can be attributed to a
    # controller.
    case_shapes: dict[str, str] = {
        name: case_shape(case["path"]) for name, case in cases.items()
    }

    lines: list[str] = []
    lines.append("---")
    lines.append("tags: [fact, generated, ledger]")
    lines.append("---")
    lines.append("")
    lines.append("# Capability ledger — what the port actually does")
    lines.append("")
    lines.append("GENERATED by `tools/knowledge/gen_capability_ledger.py`. Do not edit by hand.")
    lines.append("")
    lines.append("One row per Canvas controller — one capability. The columns are read from")
    lines.append("committed artefacts: the parity manifest (the routes), the recorded corpus")
    lines.append("(the answers Canvas gave) and the replay report (what the port answered).")
    lines.append("")
    lines.append("**A capability with no recorded case is not verified.** The corpus is the")
    lines.append("only evidence of behaviour, so a controller with no case has an unknown")
    lines.append("verdict, not a passing one.")
    lines.append("")

    total_capabilities = len(by_controller)
    recorded_capabilities = 0
    all_passed: set[str] = set()
    all_failed: set[str] = set()

    rows: list[tuple] = []
    for controller, controller_routes in sorted(by_controller.items()):
        shapes = {api_shape(r["path"]) for r in controller_routes}
        crates: set[str] = set()
        for shape in shapes:
            crates.update(registrations.get(shape, []))
        case_names = [name for name, shape in case_shapes.items() if shape in shapes]
        passed = [name for name in case_names if verdict.get(name) == "pass"]
        failed = [name for name in case_names if verdict.get(name) == "fail"]
        all_passed.update(passed)
        all_failed.update(failed)
        if case_names:
            recorded_capabilities += 1

        if not case_names:
            state = "not covered by the corpus"
        elif not failed:
            state = "matches the recorded answers"
        else:
            shapes_seen: collections.Counter = collections.Counter()
            for name in failed:
                for shape in failures.get(name, []):
                    shapes_seen[shape] += 1
            top = ", ".join(f"{s} ×{n}" for s, n in shapes_seen.most_common(2))
            state = f"differs — {top}" if top else "differs"

        rows.append((
            controller,
            canvas_controller_file(controller),
            ", ".join(sorted(crates)) or "—",
            len(controller_routes),
            len(case_names),
            len(passed),
            len(failed),
            state,
        ))

    lines.append("## The headline")
    lines.append("")
    lines.append("| Dimension | Count |")
    lines.append("|---|---:|")
    lines.append(f"| Canvas capabilities (controllers with API routes) | {total_capabilities} |")
    lines.append(f"| Capabilities with a recorded answer | {recorded_capabilities} |")
    lines.append(f"| Capabilities with no recorded answer | {total_capabilities - recorded_capabilities} |")
    lines.append(f"| Recorded cases the port reproduces | {len(all_passed)} |")
    lines.append(f"| Recorded cases the port does not reproduce | {len(all_failed)} |")
    unattributed = len(cases) - len(all_passed) - len(all_failed)
    if unattributed:
        lines.append(f"| Recorded cases not attributed to a capability | {unattributed} |")
    lines.append("")
    lines.append("## Every capability")
    lines.append("")
    lines.append("| Capability | Canvas source | Rust owner | routes | cases | pass | fail | verdict |")
    lines.append("|---|---|---|---:|---:|---:|---:|---|")
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    lines.append("")

    out = REPO / "docs" / "knowledge" / "facts" / "capability-ledger.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(REPO)} ({len(rows)} capabilities, "
          f"{len(all_passed)} pass, {len(all_failed)} fail)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
